CREATE TABLE users (
    id uuid PRIMARY KEY NOT NULL DEFAULT gen_random_uuid(),
    username text NOT NULL UNIQUE CHECK (LENGTH(username) <= 20),
    displayname text NOT NULL CHECK (LENGTH(displayname) <= 20),
    userid int NOT NULL UNIQUE CHECK (userid > 0),
    email text NOT NULL UNIQUE CHECK (email ~* '^.+@.+\..+$'),
    password text NOT NULL,
    bio text DEFAULT '',
    followers text[] DEFAULT '{}'::text[],
    following text[] DEFAULT '{}'::text[],
    profilepicture text,
    profilebanner text,
    isbanned boolean NOT NULL DEFAULT FALSE,
    isorganisation boolean NOT NULL DEFAULT FALSE,
    isdeveloper boolean NOT NULL DEFAULT FALSE,
    isverified boolean NOT NULL DEFAULT FALSE,
    isowner boolean NOT NULL DEFAULT FALSE,
    ispartner boolean NOT NULL DEFAULT FALSE,
    ismoderator boolean NOT NULL DEFAULT FALSE,
    isprivatehearts boolean NOT NULL DEFAULT FALSE,
    isprivate boolean NOT NULL DEFAULT FALSE,
    links text[] DEFAULT '{}'::text[],
    temp_password_expiry timestamp with time zone DEFAULT NULL CHECK (temp_password_expiry > CURRENT_TIMESTAMP),
    createdat timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);